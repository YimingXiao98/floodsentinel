def normalize_county_name(county: str) -> str:
    """Strip trailing ' County' for lookup parity with bootstrap storage."""
    c = county.strip()
    if c.lower().endswith(" county"):
        return c[: -len(" county")].strip()
    return c


def normalize_state(state: str) -> str:
    """Map full state names to 2-letter codes; pass through abbreviations."""
    s = state.strip()
    if not s:
        return s
    if len(s) == 2:
        return s.upper()
    return STATE_NAME_TO_CODE.get(s.lower(), s)
